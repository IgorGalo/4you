//Para fazer a ProgressBarr progredir    
    private void Swing() {
        SwingWorker progresso = new SwingWorker() {
            @Override
            protected Object doInBackground() throws Exception {
                while (barra.getValue() < 100) {
                    barra.setValue(barra.getValue() + 25);
                    Thread.sleep(500);
                }
                return null;
            }
        };
        progresso.execute();
    }

